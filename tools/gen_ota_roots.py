#!/usr/bin/env python3
"""
Regenerate adblock-esp32/src/ota_roots.h from the Mozilla root store (certifi).

Firmware updates are fetched over HTTPS and these roots are what the board
trusts for that connection. GitHub Pages and release downloads currently chain
to ISRG Root X1 and github.com to USERTrust/Sectigo; the others are here so a
CA change at GitHub doesn't silently stop updates.

    pip install certifi && python tools/gen_ota_roots.py
"""
import os
import re

import certifi

LABELS = [
    "ISRG Root X1",
    "ISRG Root X2",
    "USERTrust RSA Certification Authority",
    "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "GTS Root R1",
    "GTS Root R4",
    "Amazon Root CA 1",
]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "adblock-esp32", "src", "ota_roots.h")


def main():
    text = open(certifi.where(), encoding="utf-8").read()
    blocks = re.findall(r'# Label: "([^"]+)"\n.*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)',
                        text, re.S)
    found = {label: pem for label, pem in blocks}
    missing = [l for l in LABELS if l not in found]
    if missing:
        raise SystemExit(f"not in certifi bundle: {missing}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("#pragma once\n// Generated by tools/gen_ota_roots.py - do not edit by hand.\n")
        f.write("// Root CAs trusted for firmware-update downloads.\n")
        f.write("static const char OTA_ROOT_CAS[] =\n")
        for label in LABELS:
            f.write(f"    // {label}\n")
            for line in found[label].splitlines():
                f.write(f'    "{line}\\n"\n')
        f.write("    ;\n")
    print(f"wrote {OUT} ({len(LABELS)} roots)")


if __name__ == "__main__":
    main()
